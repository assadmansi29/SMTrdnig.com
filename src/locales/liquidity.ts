export function liquidityText(text: string, language: LanguageCode, params: Record<string, string | number> = {}): string {
  const translated = language === 'en' ? text : messages[text]?.[language] || text;
  return translated.replace(/\{(\w+)\}/g, (match, key) => String(params[key] ?? match));
}

export function liquidityError(text: string, language: LanguageCode): string {
  const binance = /^Binance market data unavailable \((\d+)\)$/.exec(text);
  if (binance) return liquidityText('Binance market data unavailable ({status})', language, {status: binance[1]});
  return liquidityText(messages[text] ? text : 'Feed unavailable', language);
}
